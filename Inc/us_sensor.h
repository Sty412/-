#ifndef __US_SENSOR_H
#define __US_SENSOR_H

#include <stdint.h>

/* ======================================================================
 * 文件：us_sensor.h
 * 用途：4路超声波传感器（RS485/Modbus RTU）的接口定义
 * 硬件：4个超声波模块，地址分别为 01~04，共享 RS485 总线
 * 波特率：9600（由 Force_USART_Baudrates() 在 main.c 中覆盖设置）
 * ====================================================================== */

/* 4路超声波模块的 Modbus 地址 */
#define US_ADDR1    1
#define US_ADDR2    2
#define US_ADDR3    3
#define US_ADDR4    4

/* 【可微调】超声波盲区边界（单位：毫米）
 * 说明：传感器在 <80mm 时返回值会乱跳（物理盲区），
 *       读到 <80mm 时系统进入"盲区锁定"，强制视为 0mm（紧急报警）
 * 建议：如果实际测试发现 80mm 还是偶尔乱跳，可提高到 100mm */
#define US_BLIND_MM     80.0f

/* 【可微调】盲区保持计数（单位：帧，每帧约 100ms）
 * 说明：进入盲区后，锁定 60 帧（约 6 秒），期间强制紧急报警。
 *       只有当读到 >=80mm 时才可能提前解除。
 * 建议：如果希望盲区保持更久/更短，可调整此值 */
#define BLIND_HOLD_CNT     60

/* 【可微调】盲区解除的安全确认次数（单位：帧）
 * 说明：盲区期间读到 >=80mm 时，需要连续 3 帧确认才解除盲区。
 *       这是核心防闪断机制：近距离时传感器可能偶发跳出 100mm、200mm
 *       甚至 500mm 的假数据，如果单帧或 2 帧就解除，报警会中断一下。
 *       连续 3 帧（约 300ms）确认后才解除，可有效过滤假数据。
 * 建议：如果现场闪断仍然发生，可增大到 4 或 5 */
#define BLIND_SAFE_EXIT_CNT 3

/* 串口接收缓冲区大小（单位：字节）
 * 说明：防止异常数据溢出写坏内存，超出的字节直接丢弃 */
#define SENSOR_RX_BUF_SIZE  32

/* ======================================================================
 * 报警阈值定义（距离，单位：毫米）
 * ====================================================================== */
#define DIST_NORMAL     120.0f   /* >=120mm：正常，无报警 */
#define DIST_LEVEL1     100.0f   /* 100~120mm：一级报警（慢闪） */
/* 80~100mm：二级报警（快闪），阈值由 US_BLIND_MM 隐含 */
/* <80mm：三级/紧急报警（常亮） */

/* 跳变检测阈值（单位：毫米）
 * 说明：相邻两帧距离变化超过 200mm，视为异常跳变，触发紧急报警 */
#define DIST_JUMP_MM    200.0f

/* 无回波最大容忍次数（单位：次）
 * 说明：连续查询 3 次都失败，认为该传感器故障，触发紧急报警 */
#define NO_ECHO_MAX     3

/* ======================================================================
 * 函数声明
 * ====================================================================== */

/* 清除 USART2 错误标志并清空接收寄存器，避免旧数据干扰下一帧 */
void US_ClearErrors(void);

/* 向指定地址的超声波发送 Modbus 查询帧，并轮询接收应答
 * 参数：addr - 传感器地址(1~4)；buf - 接收缓冲区；len - 返回接收长度
 * 返回：1=收到数据；0=超时未收到
 * 注意：本函数内部阻塞约 25ms，由调用方控制总时机 */
uint8_t US_QueryRaw(uint8_t addr, uint8_t *buf, uint8_t *len);

/* 解析超声波应答帧，更新距离和盲区状态
 * 参数：buf/len - 接收到的数据；expected_addr - 期望的地址(1~4)
 * 返回：1=解析成功；0=帧格式/CRC错误
 * 注意：即使返回 1，距离也可能被强制设为 0（盲区期间） */
uint8_t US_ParseResponse(uint8_t *buf, uint8_t len, uint8_t expected_addr);

/* ======================================================================
 * 全局变量（在 us_sensor.c 中定义，其他文件通过 extern 引用）
 * ====================================================================== */

extern float us_dist_mm[4];       /* 4路超声波当前距离（单位：mm），盲区/故障时为 0 或 9999 */
extern float us_dist_last[4];     /* 上一帧距离，用于跳变检测 */
extern uint8_t us_no_echo_cnt[4]; /* 无回波计数器，>=NO_ECHO_MAX 视为故障 */
extern uint8_t us_blind_cnt[4];   /* 盲区倒计时，>0 表示处于盲区锁定状态 */
extern uint8_t us_blind_safe_cnt[4]; /* 盲区解除安全确认计数器 */

/* 传感器在线标志：1=该路超声波至少成功收到过一帧有效数据
 * 说明：只有在线后，无回波检测才会触发紧急报警。
 *       上电时传感器未通电/未接线，不会误报警。
 *       收到第一帧有效数据后自动置位，软件复位前不会清零。 */
extern uint8_t us_online[4];

#endif
