/* ======================================================================
 * 文件：hmi.h
 * 用途：串口屏（HMI）显示接口
 * 硬件：大彩 DC48270DN043 四寸串口屏，接 USART1（PA9/PA10）
 * 波特率：115200（与调试串口共用，需外接串口屏时拔掉 USB-TTL）
 *
 * 说明：本模块提供两种输出模式，通过下面宏定义切换：
 *       - HMI_MODE_ASCII（默认）：输出文本字符串，兼容串口助手调试
 *       - HMI_MODE_DGUS：输出大彩 DGUS 二进制协议帧（需配置 VP 地址）
 *
 * 【重要】USART1 当前同时用于调试打印（debug.c）和 HMI 输出。
 *         外接串口屏时，请拔掉 USB-TTL，避免总线冲突。
 * ====================================================================== */

#ifndef __HMI_H
#define __HMI_H

#include <stdint.h>

/* ======================================================================
 * 模式选择（二选一，注释掉另一个）
 * ====================================================================== */
#define HMI_MODE_ASCII    /* 默认：ASCII 文本输出，兼容调试 */
// #define HMI_MODE_DGUS  /* 大彩 DGUS 二进制协议（需配置下方 VP 地址） */

/* ======================================================================
 * DGUS 模式配置（仅在 HMI_MODE_DGUS 时生效）
 * 说明：VP 地址是串口屏变量存储器地址，在 DGUS Tool 中配置控件时设定。
 *       以下地址为预留示例，请根据实际界面设计修改。
 * ====================================================================== */
#ifdef HMI_MODE_DGUS
  #define HMI_VP_US1      0x1000   /* US1 距离显示控件 VP 地址 */
  #define HMI_VP_US2      0x1001   /* US2 距离显示控件 VP 地址 */
  #define HMI_VP_US3      0x1002   /* US3 距离显示控件 VP 地址 */
  #define HMI_VP_US4      0x1003   /* US4 距离显示控件 VP 地址 */
  #define HMI_VP_TILT     0x1004   /* 倾角显示控件 VP 地址 */
  #define HMI_VP_ALARM    0x1005   /* 报警等级显示控件 VP 地址（0~4） */
#endif

/* ======================================================================
 * 刷新间隔（单位：毫秒）
 * 说明：避免刷屏过快导致串口屏卡顿，建议 200~500ms
 * 【可微调】如果屏幕显示有延迟感，可增大到 500；如果需要更实时，可减小到 100
 * ====================================================================== */
#define HMI_UPDATE_MS   300

/* ======================================================================
 * 函数声明
 * ====================================================================== */

/* 刷新串口屏显示（在 Sensor_Task 末尾调用）
 * 说明：根据当前传感器数据和报警等级，更新屏幕显示 */
void HMI_Update(void);

#endif
