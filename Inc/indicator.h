#ifndef __INDICATOR_H
#define __INDICATOR_H

#include <stdint.h>

/* ======================================================================
 * 文件：indicator.h
 * 用途：声光报警指示器驱动（LED + 蜂鸣器）
 * 硬件连接：
 *   - PC13：板载绿色 LED（整体报警状态，高电平=灭，低电平=亮）
 *   - PB0：  蜂鸣器（高电平触发=响，低电平=静音）
 *   - PB1：  外接红色 LED（与蜂鸣器同步，高电平=亮，低电平=灭）
 * 【重要】如果更换蜂鸣器或 LED 的接线方式，需修改下面的宏定义
 * ====================================================================== */

/* 【可微调】蜂鸣器触发方式选择
 * 说明：当前蜂鸣器是"高电平触发"（给高电平就响）。
 *       如果换成低电平触发的蜂鸣器，把这行注释掉，取消注释下一行 */
#define BUZZER_HIGH_TRIGGER
/* #define BUZZER_LOW_TRIGGER */

/* ======================================================================
 * 函数声明
 * ====================================================================== */

/* 初始化 GPIO（PC13、PB0、PB1），并做上电自检闪烁 */
void Indicator_Init(void);

/* 更新 PC13 板载灯（绿色）：反映整体报警等级
 * 参数：level - alarm_level（0~4） */
void LED_PC13_Update(uint8_t level);

/* 更新 PB1 外接红灯：反映整体报警等级（与蜂鸣器同步）
 * 参数：level - alarm_level（0~4） */
void LED_PB1_Update(uint8_t tilt_level);

/* 更新 PB0 蜂鸣器：反映整体报警等级
 * 参数：level - alarm_level（0~4） */
void Buzzer_Update(uint8_t level);

#endif
