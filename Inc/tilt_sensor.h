#ifndef __TILT_SENSOR_H
#define __TILT_SENSOR_H

#include <stdint.h>

/* ======================================================================
 * 文件：tilt_sensor.h
 * 用途：倾角传感器（RS232/Modbus RTU）的接口定义
 * 硬件：SMSA11-v15，单轴 Roll，Modbus 地址 05
 * 波特率：115200（由 Force_USART_Baudrates() 在 main.c 中覆盖设置）
 * 量程：Roll ±15°
 * ====================================================================== */

/* 倾角传感器的 Modbus 地址 */
#define TILT_ADDR   5

/* ======================================================================
 * 函数声明
 * ====================================================================== */

/* 清除 USART3 错误标志并清空接收寄存器 */
void Tilt_ClearErrors(void);

/* 向倾角传感器发送 Modbus 查询帧，并轮询接收应答
 * 参数：buf - 接收缓冲区；len - 返回接收长度
 * 返回：1=收到数据；0=超时未收到
 * 注意：本函数内部阻塞约 25ms */
uint8_t Tilt_QueryRaw(uint8_t *buf, uint8_t *len);

/* 解析倾角传感器应答帧，提取 Roll 角度
 * 参数：buf/len - 接收到的数据
 * 返回：1=解析成功；0=帧格式/CRC错误 */
uint8_t Tilt_ParseResponse(uint8_t *buf, uint8_t len);

/* ======================================================================
 * 全局变量
 * ====================================================================== */

extern float tilt_roll;   /* 当前 Roll 角度（单位：度），范围约 ±15° */
extern float tilt_pitch;  /* 预留，当前固定为 0 */
extern float tilt_yaw;    /* 预留，当前固定为 0 */

#endif
